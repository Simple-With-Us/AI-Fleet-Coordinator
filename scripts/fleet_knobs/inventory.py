"""The INFISICAL.md knob table, generated from the registry so the two cannot drift.

``python3 -m fleet_knobs inventory --check INFISICAL.md`` exits 1 when the generated block
between the two marker comments differs from the file;  ``--write`` rewrites the block.
"""
from __future__ import annotations

from typing import List

from . import values
from .registry import REGISTRY, Spec

BEGIN = ("<!-- fleet-knobs:begin  generated by `python3 -m fleet_knobs inventory --write "
         "../INFISICAL.md`;  edit scripts/fleet_knobs/registry.py, not this block -->")
END = "<!-- fleet-knobs:end -->"
HEADER = ("| Key | Owner | Kind | Default | Secret | Local files may | What it does |\n"
          "|---|---|---|---|---|---|---|")


def _kind(spec: Spec) -> str:
    if spec.kind == "enum":
        return "enum: " + " < ".join(spec.choices)
    if spec.kind == "int" and spec.maximum is not None:
        return f"int {spec.minimum} to {spec.maximum}"
    return spec.kind


def _default(spec: Spec) -> str:
    if spec.secret:
        return "none, fails closed"
    if spec.default is None:
        # A knob with no default has no value until somebody sets one,  so the table
        # says "unset" rather than printing a Python None.
        return "unset"
    shown = values.render(spec, values.default_value(spec))
    return f"`{shown}`" if shown else {"list": "empty", "str": "unset"}.get(spec.kind, "empty")


def _local(spec: Spec) -> str:
    if spec.local == "deny":
        return "nothing"
    return {
        "bool": f"only set it to `{str(spec.safe).lower()}`",
        "enum": f"only move toward `{spec.choices[0]}`" if spec.kind == "enum" else "",
        "int": "only lower it" if spec.narrower == "min" else "only raise it",
        "list": "only remove entries",
        "caps": "only lower a number",
        "str": "nothing",
    }[spec.kind]


def rows() -> List[str]:
    out = []
    for spec in REGISTRY:
        cells = [f"`{spec.name}`", spec.owner, _kind(spec), _default(spec),
                 "secret" if spec.secret else "no", _local(spec), spec.note]
        out.append("| " + " | ".join(c.replace("|", "/") for c in cells) + " |")
    return out


def block() -> str:
    return "\n".join([BEGIN, "", HEADER] + rows() + ["", END])


def _bounds(text: str):
    start, end = text.find("<!-- fleet-knobs:begin"), text.find(END)
    if start < 0 or end < start:
        return None
    return start, end + len(END)


def check(text: str) -> bool:
    found = _bounds(text)
    return bool(found) and text[found[0]:found[1]] == block()


def splice(text: str) -> str:
    """`text` with the generated block replaced (it must already carry the markers)."""
    found = _bounds(text)
    if not found:
        raise ValueError("the file has no fleet-knobs marker block")
    return text[:found[0]] + block() + text[found[1]:]
