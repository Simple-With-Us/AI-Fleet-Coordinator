class CollectionError(RuntimeError):
    """A safe, user-facing collection failure."""


@dataclass(frozen=True)
class RepoInfo:
    path: Path
    owner: str
    name: str
    ref: str
    commit: str


@dataclass(frozen=True)
class Blob:
    path: str
    mode: str
    object_id: str


def _run_git(repo: Path, *args: str, check: bool = True) -> bytes:
    try:
        result = subprocess.run(
            ["git", "--no-replace-objects", "-C", str(repo), *args],
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            check=False,
            env={
                "PATH": os.environ.get("PATH", "/usr/bin:/bin"),
                "GIT_OPTIONAL_LOCKS": "0",
                "GIT_CONFIG_NOSYSTEM": "1",
                "GIT_CONFIG_GLOBAL": os.devnull,
                "GIT_TERMINAL_PROMPT": "0",
            },
        )
    except OSError as exc:
        raise CollectionError("git could not be started") from exc
    if check and result.returncode != 0:
        raise CollectionError("Git metadata or object read failed")
    return result.stdout if result.returncode == 0 else b""


def _github_owner_repo(remote: str) -> tuple[str, str] | None:
    value = remote.strip()
    if value.startswith("git@github.com:"):
        suffix = value.removeprefix("git@github.com:")
    else:
        parsed = urlsplit(value)
        if parsed.scheme not in {"https", "ssh", "git"} or (
            parsed.hostname or ""
        ).casefold() not in {
            "github.com",
            "www.github.com",
        }:
            return None
        suffix = parsed.path.lstrip("/")
    suffix = suffix.removesuffix(".git")
    parts = suffix.split("/")
    if len(parts) != 2 or not all(GITHUB_REPO_RE.fullmatch(part) for part in parts):
        return None
    if parts[0] in {".", ".."} or parts[1] in {".", ".."}:
        return None
    return parts[0], parts[1]


def _repo_info(path: Path) -> RepoInfo | None:
    if path.is_symlink() or not path.is_dir() or SCRATCH_RE.match(path.name):
        return None
    try:
        top = Path(os.fsdecode(_run_git(path, "rev-parse", "--show-toplevel").strip())).resolve()
        resolved = path.resolve()
        if top != resolved:
            return None
        remote = os.fsdecode(_run_git(path, "remote", "get-url", "origin").strip())
        parsed = _github_owner_repo(remote)
        if parsed is None:
            return None
        main_commit = _run_git(
            path, "rev-parse", "--verify", "refs/remotes/origin/main^{commit}", check=False
        ).strip()
        if main_commit:
            ref = "origin/main"
            commit_bytes = main_commit
        else:
            default_ref = os.fsdecode(
                _run_git(
                    path, "symbolic-ref", "--quiet", "refs/remotes/origin/HEAD", check=False
                ).strip()
            )
            if (
                not default_ref.startswith("refs/remotes/origin/")
                or default_ref == "refs/remotes/origin/HEAD"
            ):
                return None
            ref = default_ref.removeprefix("refs/remotes/")
            commit_bytes = _run_git(
                path, "rev-parse", "--verify", f"{default_ref}^{{commit}}", check=False
            ).strip()
        commit = os.fsdecode(commit_bytes)
        if not re.fullmatch(r"[0-9a-fA-F]{40,64}", commit):
            return None
        return RepoInfo(
            path=resolved, owner=parsed[0], name=parsed[1], ref=ref, commit=commit.lower()
        )
    except (CollectionError, OSError, UnicodeError):
        return None


def discover_repositories(
    code_root: Path | None,
    requested: str | None = None,
    repo_paths: list[Path] | None = None,
) -> tuple[list[RepoInfo], list[str]]:
    candidates: list[RepoInfo] = []
    if repo_paths:
        for path in sorted(
            {Path(item).expanduser() for item in repo_paths}, key=lambda item: str(item).casefold()
        ):
            info = _repo_info(path)
            if info is not None and (requested is None or info.name == requested):
                candidates.append(info)
    else:
        if code_root is None or not code_root.is_dir() or code_root.is_symlink():
            raise CollectionError("Code root must be an existing real directory")
        for entry in sorted(code_root.iterdir(), key=lambda item: item.name.casefold()):
            info = _repo_info(entry)
            if info is not None and (requested is None or info.name == requested):
                candidates.append(info)

    groups: dict[tuple[str, str], list[RepoInfo]] = {}
    for info in candidates:
        groups.setdefault((info.owner.casefold(), info.name.casefold()), []).append(info)

    selected: list[RepoInfo] = []
    skipped: list[str] = []
    identities_by_name: dict[str, set[tuple[str, str]]] = {}
    for group in groups.values():
        identity = (group[0].owner.casefold(), group[0].name.casefold())
        identities_by_name.setdefault(group[0].name.casefold(), set()).add(identity)
    for key, group in sorted(groups.items()):
        owners_names = {(repo.owner.casefold(), repo.name.casefold()) for repo in group}
        name_key = group[0].name.casefold()
        if len(identities_by_name.get(name_key, set())) > 1:
            skipped.extend(repo.path.name for repo in group)
            continue
        # Prefer an exact local folder match to the GitHub repository name.
        group.sort(key=lambda repo: (repo.path.name != repo.name, repo.path.name.casefold()))
        if len(owners_names) > 1:
            skipped.extend(repo.path.name for repo in group)
            continue
        selected.append(group[0])
        skipped.extend(repo.path.name for repo in group[1:])
    if requested and not selected:
        raise CollectionError(f"No top-level GitHub repository named {requested!r} was found")
    return selected, skipped


def _parse_tree(repo: RepoInfo) -> dict[str, Blob]:
    raw = _run_git(repo.path, "ls-tree", "-rz", "--full-tree", repo.commit)
    files: dict[str, Blob] = {}
    for record in raw.split(b"\0"):
        if not record:
            continue
        try:
            metadata, path_bytes = record.split(b"\t", 1)
            mode, object_type, object_id = metadata.decode("ascii").split(" ")
            relative = os.fsdecode(path_bytes)
        except (ValueError, UnicodeError):
            continue
        if object_type != "blob":
            continue
        if not _safe_relative(relative):
            continue
        files[relative] = Blob(path=relative, mode=mode, object_id=object_id)
    return files


def _safe_relative(value: str) -> bool:
    if not value or "\\" in value or any(ord(char) < 0x20 or ord(char) == 0x7F for char in value):
        return False
    path = PurePosixPath(value)
    return not path.is_absolute() and all(part not in {"", ".", ".."} for part in path.parts)


def _sensitive_path(relative: str, allow_private_audit: bool = False) -> bool:
    path = PurePosixPath(relative)
    parts = [part.casefold() for part in path.parts]
    allowed_parts = (
        {"private-audits"}
        if allow_private_audit and parts[:2] == ["docs", "private-audits"]
        else set()
    )
    if any(part in SENSITIVE_DIRS and part not in allowed_parts for part in parts):
        return True
    name = path.name.casefold()
    if name == ".env" or name.startswith(".env.") or name.endswith(".env"):
        return True
    if name in {"credentials.json", "auth.json", "secrets.json", "secrets.yaml", "secrets.yml"}:
        return True
    return Path(name).suffix in SENSITIVE_SUFFIXES


def _is_human_document(relative: str, allow_private_audit: bool = False) -> bool:
    private_audit_path = relative.casefold().startswith("docs/private-audits/")
    if not _safe_relative(relative) or _sensitive_path(
        relative, allow_private_audit=allow_private_audit
    ):
        return False
    path = PurePosixPath(relative)
    suffix = Path(path.name).suffix.casefold()
    if suffix not in DOCUMENT_SUFFIXES:
        return False
    if private_audit_path:
        return allow_private_audit
    components = [part.casefold() for part in path.parts[:-1]]
    if any(part in DOCUMENT_DIRS for part in components):
        return True
    if len(path.parts) == 1 or (len(path.parts) == 2 and path.parts[0].casefold() == "docs"):
        stem = path.stem.casefold()
        return any(
            stem == prefix or stem.startswith(f"{prefix}-") or stem.startswith(f"{prefix}_")
            for prefix in ROOT_DOC_PREFIXES
        )
    return False


LINK_RE = re.compile(r"!?\[[^\]]*\]\(<?([^\s)>]+)>?(?:\s+['\"].*?['\"])?\)")
REFERENCE_RE = re.compile(r"^\s*\[[^\]]+\]:\s*<?([^\s>]+)>?", re.MULTILINE)
RST_LINK_RE = re.compile(
    r"`[^`<>]+\s*<([^>]+)>`_|^\s*\.\.\s+(?:image|figure)::\s*(\S+)", re.MULTILINE
)


def _local_targets(content: bytes, source_path: str) -> set[str]:
    try:
        text = content.decode("utf-8")
    except UnicodeDecodeError:
        return set()
    raw_targets = [match.group(1) for match in LINK_RE.finditer(text)]
    raw_targets.extend(match.group(1) for match in REFERENCE_RE.finditer(text))
    for match in RST_LINK_RE.finditer(text):
        target = match.group(1) or match.group(2)
        if target:
            raw_targets.append(target)

    targets: set[str] = set()
    parent = PurePosixPath(source_path).parent
    for raw in raw_targets:
        target = unquote(raw.strip().strip("<>"))
        if not target or target.startswith(("#", "/", "//")):
            continue
        try:
            parsed = urlsplit(target)
        except ValueError:
            continue
        if parsed.scheme or parsed.netloc:
            continue
        path_text = parsed.path
        if not path_text:
            continue
        parts: list[str] = []
        for part in (parent / PurePosixPath(path_text)).parts:
            if part in {"", ".", "/"}:
                continue
            if part == "..":
                if not parts:
                    parts = []
                    break
                parts.pop()
            else:
                parts.append(part)
        if parts:
            candidate = PurePosixPath(*parts).as_posix()
            if _safe_relative(candidate):
                targets.add(candidate)
    return targets


def _select_blobs(
    repo: RepoInfo,
    tree: dict[str, Blob],
    include_private_audits: bool = False,
) -> tuple[dict[str, Blob], dict[str, bytes], list[dict[str, str]]]:
    selected = {
        path: blob
        for path, blob in tree.items()
        if blob.mode in {"100644", "100755"}
        and _is_human_document(path, allow_private_audit=include_private_audits)
    }
    content: dict[str, bytes] = {}
    missing: set[tuple[str, str]] = set()
    pending = list(selected)
    while pending:
        source_path = pending.pop()
        if source_path in content:
            continue
        blob = tree[source_path]
        data = _run_git(repo.path, "show", f"{repo.commit}:{source_path}")
        content[source_path] = data
        for target in _local_targets(data, source_path):
            linked = tree.get(target)
            private_target = include_private_audits and target.casefold().startswith(
                "docs/private-audits/"
            )
            if (
                linked is None
                or linked.mode not in {"100644", "100755"}
                or _sensitive_path(target, allow_private_audit=private_target)
            ):
                if (
                    Path(target).suffix.casefold()
                    in DOCUMENT_SUFFIXES | ASSET_SUFFIXES | LINKED_EVIDENCE_SUFFIXES
                    and not _sensitive_path(target, allow_private_audit=private_target)
                ):
                    missing.add((source_path, target))
                continue
            suffix = Path(target).suffix.casefold()
            if suffix not in DOCUMENT_SUFFIXES | ASSET_SUFFIXES | LINKED_EVIDENCE_SUFFIXES:
                continue
            if suffix in DOCUMENT_SUFFIXES and not _is_human_document(
                target, allow_private_audit=private_target
            ):
                continue
            if suffix in LINKED_EVIDENCE_SUFFIXES and not target.casefold().startswith("docs/"):
                continue
            if target not in selected:
                selected[target] = linked
                pending.append(target)
    missing_links = [
        {"source_path": source, "target_path": target} for source, target in sorted(missing)
    ]
    return selected, content, missing_links


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _json_bytes(value: Any) -> bytes:
    return (json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n").encode("utf-8")


def _safe_output_path(root: Path, relative: str) -> Path:
    if not _safe_relative(relative):
        raise CollectionError("Unsafe output path")
    absolute_root = Path(os.path.abspath(root))
    current_root = Path(absolute_root.anchor)
    for part in absolute_root.parts[1:]:
        current_root = current_root / part
        if current_root.is_symlink():
            raise CollectionError("Output root path contains a symlink")
    root = absolute_root
    target = root.joinpath(*PurePosixPath(relative).parts)
    current = root
    for part in PurePosixPath(relative).parts:
        current = current / part
        if current.is_symlink():
            raise CollectionError("Output path contains a symlink")
    try:
        target.parent.resolve().relative_to(root)
    except ValueError as exc:
        raise CollectionError("Output path escapes the library root") from exc
    return target


def _read_existing(path: Path) -> bytes | None:
    if not path.exists() and not path.is_symlink():
        return None
    if path.is_symlink() or not path.is_file():
        raise CollectionError("An existing output path is not a regular file")
    if stat.S_IMODE(path.stat(follow_symlinks=False).st_mode) != 0o600:
        raise CollectionError("An existing collection file is not owner-only")
    return path.read_bytes()


def _load_previous_manifest(path: Path, repo_name: str) -> dict[str, Any]:
    raw = _read_existing(path)
    if raw is None:
        return {}
    try:
        value = json.loads(raw)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise CollectionError("Existing manifest is not a recognized generated manifest") from exc
    if (
        value.get("schema_version") != SCHEMA_VERSION
        or value.get("generated_by") != "collect-repo-documents.py"
        or value.get("repo") != repo_name
        or not isinstance(value.get("source_ref"), str)
        or not isinstance(value.get("source_commit"), str)
        or not re.fullmatch(r"[0-9a-f]{40,64}", value.get("source_commit", ""))
        or not isinstance(value.get("owner_repo"), str)
        or "/" not in value.get("owner_repo", "")
    ):
        raise CollectionError("Existing manifest is not owned by this collector")
    return value


def _preflight_file(
    path: Path, data: bytes, previous_hash: str | None = None, immutable: bool = False
) -> bool:
    old = _read_existing(path)
    if old is None:
        return True
    if old == data:
        return False
    if immutable:
        raise CollectionError("A versioned report already exists with different content")
    if previous_hash is None or _sha256(old) != previous_hash:
        raise CollectionError("An existing output was changed or is not collector-owned")
    return True


def _check_private_directory(path: Path) -> None:
    if path.is_symlink() or not path.is_dir():
        raise CollectionError("A collection directory is not a real directory")
    mode = stat.S_IMODE(path.stat(follow_symlinks=False).st_mode)
    if mode != 0o700:
        raise CollectionError(
            f"An existing collection directory must have mode 0700 (found {mode:04o}): {path}"
        )


def _ensure_private_directory(path: Path, boundary: Path, create: bool) -> bool:
    boundary_abs = Path(os.path.abspath(boundary))
    path_abs = Path(os.path.abspath(path))
    try:
        relative = path_abs.relative_to(boundary_abs)
    except ValueError as exc:
        raise CollectionError("Collection directory escapes the output root") from exc

    if boundary_abs.exists() or boundary_abs.is_symlink():
        _check_private_directory(boundary_abs)
    elif create:
        if not boundary_abs.parent.is_dir() or boundary_abs.parent.is_symlink():
            raise CollectionError("Output root parent must already be a real directory")
        os.mkdir(boundary_abs, 0o700)
        os.chmod(boundary_abs, 0o700, follow_symlinks=False)
        _check_private_directory(boundary_abs)
    else:
        return False

    current = boundary_abs
    for part in relative.parts:
        current = current / part
        if current.exists() or current.is_symlink():
            _check_private_directory(current)
        elif create:
            os.mkdir(current, 0o700)
            os.chmod(current, 0o700, follow_symlinks=False)
            _check_private_directory(current)
        else:
            return False
    return True


def _atomic_write(path: Path, data: bytes, boundary: Path) -> None:
    _ensure_private_directory(path.parent, boundary, create=True)
    fd, temp_name = tempfile.mkstemp(prefix=".collect-docs-", dir=path.parent)
    temp = Path(temp_name)
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        if path.is_symlink():
            raise CollectionError("Refusing to replace an output symlink")
        os.replace(temp, path)
        if stat.S_IMODE(path.stat(follow_symlinks=False).st_mode) != 0o600:
            raise CollectionError("Generated collection file is not owner-only")
    finally:
        try:
            temp.unlink()
        except FileNotFoundError:
            pass


def _markdown_link(path: str) -> str:
    return "/".join(quote(part, safe="-._~") for part in path.split("/"))


def _markdown_label(path: str) -> str:
    return path.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]").replace("`", "\\`")


def _build_manifest(
    repo: RepoInfo,
    selected: dict[str, Blob],
    content: dict[str, bytes],
    previous: dict[str, Any],
    missing_links: list[dict[str, str]],
    private_docs_opt_in: str | None = None,
) -> dict[str, Any]:
    current = {
        f"documents/{path}": {
            "source_path": path,
            "source_commit": repo.commit,
            "sha256": _sha256(content[path]),
        }
        for path in sorted(selected)
    }
    # Retain removed source files so a new collection never destroys a historical copy.
    for path, item in previous.get("files", {}).items():
        if path not in current:
            current[path] = {**item, "retained": True}
    manifest = {
        "schema_version": SCHEMA_VERSION,
        "generated_by": "collect-repo-documents.py",
        "owner_repo": f"{repo.owner}/{repo.name}",
        "repo": repo.name,
        "source_ref": repo.ref,
        "source_commit": repo.commit,
        "files": dict(sorted(current.items())),
        "missing_local_links": missing_links,
    }
    if private_docs_opt_in is not None:
        manifest["private_docs_opt_in"] = private_docs_opt_in
    return manifest


def _manifest_version_key(manifest: dict[str, Any]) -> str:
    commit = str(manifest["source_commit"])
    return f"{commit}-private-docs" if manifest.get("private_docs_opt_in") else commit


def _repo_readme(repo: RepoInfo, manifest: dict[str, Any]) -> bytes:
    active = [
        entry["source_path"] for entry in manifest["files"].values() if not entry.get("retained")
    ]
    lines = [
        MARKER,
        f"# {repo.name} document mirror",
        "",
        f"Source: `{repo.owner}/{repo.name}` at `{repo.ref}` commit `{repo.commit}`.",
        "",
        "These files are copied from tracked Git objects at that commit.  Local changes and untracked files are excluded.",
        "",
        "## Documents",
        "",
    ]
    lines.extend(
        f"- [`{_markdown_label(path)}`](documents/{_markdown_link(path)})"
        for path in sorted(active)
    )
    if not active:
        lines.append("- No eligible tracked documents were found.")
    version_key = _manifest_version_key(manifest)
    lines.extend(
        [
            "",
            f"Versioned report: [reports/{version_key}/README.md](reports/{version_key}/README.md)",
            "",
        ]
    )
    if manifest.get("missing_local_links"):
        lines.extend(["## Missing linked files", ""])
        lines.extend(
            f"- `{_markdown_label(link['source_path'])}` refers to unavailable `{_markdown_label(link['target_path'])}`."
            for link in manifest["missing_local_links"]
        )
        lines.append("")
    return "\n".join(lines).encode("utf-8")


def _version_readme(repo: RepoInfo, manifest: dict[str, Any]) -> bytes:
    lines = [
        MARKER,
        f"# {repo.name} collection {repo.commit[:12]}",
        "",
        f"Source ref: `{repo.ref}` at commit `{repo.commit}`.",
        "",
        "This immutable report records the tracked documents selected for this source revision.",
        "",
        "## Included paths",
        "",
    ]
    lines.extend(
        f"- `{_markdown_label(entry['source_path'])}` — SHA-256 `{entry['sha256']}`"
        for entry in manifest["files"].values()
        if not entry.get("retained")
    )
    if len(lines) == 8:
        lines.append("- No eligible tracked documents were found.")
    lines.extend(["", "The corresponding current document copies are in `../../documents/`.", ""])
    return "\n".join(lines).encode("utf-8")


def _root_readme(repositories: list[tuple[RepoInfo, dict[str, Any]]]) -> bytes:
    lines = [
        MARKER,
        "# Repository document library",
        "",
        "Tracked-document mirrors and immutable per-commit collection reports.",
        "",
        "## Repositories",
        "",
    ]
    for repo, manifest in sorted(repositories, key=lambda item: item[0].name.casefold()):
        count = sum(1 for entry in manifest["files"].values() if not entry.get("retained"))
        lines.append(
            f"- [`{repo.name}/`](./{repo.name}/README.md) — {count} documents; source `{repo.owner}/{repo.name}` at `{repo.commit[:12]}`"
        )
    if not repositories:
        lines.append("- No matching GitHub repositories found.")
    lines.append("")
    return "\n".join(lines).encode("utf-8")


