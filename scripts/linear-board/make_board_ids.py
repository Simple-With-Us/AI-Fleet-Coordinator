#!/usr/bin/env python3
"""Regenerate board-ids.txt from the importer's board-to-linear.tsv.

Usage:  python3 scripts/linear-board/make_board_ids.py <board-to-linear.tsv> [out]

Writes only ids:  one imported board id per line, and the Linear issue UUID
after a tab when the import merged that board row into another issue (a
GitHub-keyed issue, so its UUID is not the board id).  No titles, URLs,
identifiers or anything else from the TSV.
"""
import csv
import re
import sys
from pathlib import Path

HEX32 = re.compile(r"[0-9a-f]{32}")


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    src = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent / "board-ids.txt"
    rows = {}
    with src.open(newline="") as f:
        for r in csv.DictReader(f, delimiter="\t"):
            b = (r.get("board_id") or "").strip().lower().replace("-", "")
            lin = (r.get("linear_id") or "").strip().lower().replace("-", "")
            if not HEX32.fullmatch(b) or not HEX32.fullmatch(lin):
                continue
            rows[b] = lin
    lines = ["# board id [TAB linear issue uuid when it differs].  Generated by make_board_ids.py; ids only."]
    for b in sorted(rows):
        lin = rows[b]
        lines.append(b if lin == b else f"{b}\t{lin[:8]}-{lin[8:12]}-{lin[12:16]}-{lin[16:20]}-{lin[20:]}")
    out.write_text("\n".join(lines) + "\n")
    diff = sum(1 for b, lin in rows.items() if lin != b)
    print(f"wrote {out}: {len(rows)} board ids, {diff} mapped to another issue")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
