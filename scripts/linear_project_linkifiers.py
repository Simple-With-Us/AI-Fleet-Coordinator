@dataclass(frozen=True)
class Project:
    code: str
    slug: str
    name: str


def project_url(slug: str) -> str:
    return WORKSPACE_URL + slug


def _code_sort_key(code: str) -> tuple[str, int]:
    match = _CODE_SORT_RE.match(code)
    if match:
        return (match.group(1), int(match.group(2)))
    return (code, 0)


def _projects_sorted(projects: list[Project]) -> list[Project]:
    return sorted(projects, key=lambda p: _code_sort_key(p.code))


def _linear_headers(linear_key: str) -> dict[str, str]:
    auth = "Bearer " + linear_key if linear_key.startswith("lin_oauth_") else linear_key
    return {"Authorization": auth, "Content-Type": "application/json"}


def fetch_projects_with_stats(
    linear_key: str, *, opener: Callable[..., Any] = urllib.request.urlopen
) -> tuple[list[Project], int]:
    """Every Linear project as Project, sorted by (team, number), plus the count of
    skipped nodes (identifier or slugId failing validation).  Raises LinearError with
    the GraphQL message only, never a body dump and never the key."""
    projects: list[Project] = []
    skipped = 0
    cursor: str | None = None
    for _ in range(MAX_PAGES):
        body = json.dumps({"query": GRAPHQL_QUERY, "variables": {"cursor": cursor}}).encode("utf-8")
        req = urllib.request.Request(
            LINEAR_GRAPHQL, data=body, headers=_linear_headers(linear_key), method="POST"
        )
        try:
            with opener(req, timeout=30) as resp:
                payload = json.load(resp)
        except urllib.error.HTTPError as exc:
            message = ""
            try:
                detail = json.loads(exc.read() or b"{}")
                if isinstance(detail, dict):
                    errors = detail.get("errors")
                    if isinstance(errors, list) and errors:
                        first = errors[0]
                        message = (
                            str(first.get("message", ""))[:200] if isinstance(first, dict) else ""
                        )
                    message = message or str(detail.get("message", ""))[:200]
            except (ValueError, OSError):
                message = ""
            raise LinearError(
                "Linear GraphQL: HTTP %d%s" % (exc.code, (" " + message) if message else "")
            ) from None
        except (OSError, ValueError) as exc:
            raise LinearError("Linear GraphQL: %s" % type(exc).__name__) from None
        if not isinstance(payload, dict):
            raise LinearError("Linear GraphQL: unexpected response")
        errors = payload.get("errors")
        if errors:
            if isinstance(errors, list):
                texts = [
                    str(e.get("message", ""))[:200]
                    for e in errors[:3]
                    if isinstance(e, dict) and e.get("message")
                ]
            else:
                texts = []
            raise LinearError("Linear GraphQL: %s" % ("; ".join(texts) if texts else "error"))
        try:
            connection = payload["data"]["projects"]
            nodes = connection["nodes"]
            page = connection["pageInfo"]
        except (KeyError, TypeError):
            raise LinearError("Linear GraphQL: unexpected response") from None
        if not isinstance(nodes, list) or not isinstance(page, dict):
            raise LinearError("Linear GraphQL: unexpected response")
        for node in nodes:
            if not isinstance(node, dict):
                skipped += 1
                continue
            code = node.get("identifier")
            slug = node.get("slugId")
            name = node.get("name", "")
            if (
                not isinstance(code, str)
                or not CODE_RE.match(code)
                or not isinstance(slug, str)
                or not SLUG_RE.match(slug)
            ):
                skipped += 1
                continue
            projects.append(Project(code=code, slug=slug, name=str(name or "")))
        if not page.get("hasNextPage"):
            break
        cursor = page.get("endCursor")
        if not cursor:
            break
    return _projects_sorted(projects), skipped


def fetch_projects(
    linear_key: str, *, opener: Callable[..., Any] = urllib.request.urlopen
) -> list[Project]:
    projects, skipped = fetch_projects_with_stats(linear_key, opener=opener)
    fetch_projects.last_skipped = skipped  # type: ignore[attr-defined]
    return projects


fetch_projects.last_skipped = 0  # type: ignore[attr-defined]


def slug_from_url(url: Any) -> str | None:
    """The trailing slugId of a Linear project URL (the last "-" chunk of the path),
    or None.  Used only to log which project triggered."""
    if not isinstance(url, str) or not url:
        return None
    try:
        path = urllib.parse.urlsplit(url).path.rstrip("/")
    except ValueError:
        return None
    if not path:
        return None
    chunk = path.rsplit("-", 1)[-1]
    return chunk if SLUG_RE.match(chunk) else None


def sanitize_name(name: Any) -> str:
    """Untrusted Linear text made safe for a generated comment line.  An allowlist, so
    nothing that means something to Python, the shell heredoc or the PROJECT_PATHS brace
    scan survives (no quotes, '#', backslashes, braces, '$', backticks or '*/'):  letters,
    digits, spaces and . , : ; ( ) / & + _ - only, whitespace collapsed, at most 60 chars."""
    text = str(name or "")
    while "*/" in text:
        text = text.replace("*/", "")
    text = re.sub(r"[^A-Za-z0-9 .,:;()/&+_-]", " ", re.sub(r"\s+", " ", text))
    text = re.sub(r" +", " ", text).strip()
    return text[:60].strip()


class SyncResult(list):  # type: ignore[type-arg]
    """The actions sync_zulip took, plus the live id of every code after the sync
    (re-read, so TARGET can pin ids).  A list of (kind, rule_id_or_None, code, url)."""

    def __init__(self, actions: list[tuple], ids: dict[str, int | None]) -> None:
        super().__init__(actions)
        self.ids = ids


def live_project_ids(zulip: Any, projects: list[Project]) -> dict[str, int | None]:
    """The live rule id of each code (None when the realm has no such rule)."""
    live = zulip.linkifiers()
    by_pattern = {}
    for rule in live:
        if isinstance(rule, dict) and rule.get("pattern") not in by_pattern:
            by_pattern[rule.get("pattern")] = rule
    ids: dict[str, int | None] = {}
    for project in projects:
        rule = by_pattern.get(project.code)
        rule_id = rule.get("id") if isinstance(rule, dict) else None
        ids[project.code] = rule_id if isinstance(rule_id, int) else None
    return ids


def _plan_zulip_actions(live: list[dict], projects: list[Project]) -> list[tuple]:
    by_pattern = {rule.get("pattern"): rule for rule in live if isinstance(rule, dict)}
    steps = []
    for project in _projects_sorted(list(projects)):
        want = project_url(project.slug)
        current = by_pattern.get(project.code)
        if current is None:
            steps.append(("add", None, project.code, want))
        elif current.get("url_template") != want:
            steps.append(("edit", current.get("id"), project.code, want))
    return steps


def sync_zulip(zulip: Any, projects: list[Project]) -> SyncResult:
    """Upsert one literal P-TEAM-N rule per project (ID-only URL).  Never deletes,
    never touches a non-P-* rule.  After any change the generic rule is moved back
    last (also when a call fails, like apply_plan).  Idempotent:  nothing changed
    means zero write calls."""
    import zulip_linkifiers as ZL

    live = zulip.linkifiers()
    steps = _plan_zulip_actions(live, projects)
    changed = False
    try:
        for kind, rule_id, code, url in steps:
            data = {"pattern": code, "url_template": url}
            if kind == "edit":
                zulip.call("PATCH", "realm/filters/%s" % rule_id, data)
            else:
                zulip.call("POST", "realm/filters", data)
            changed = True
    except BaseException:
        try:
            ZL.restore_order(zulip)
        except Exception:  # noqa: BLE001,S110 - the original error matters, not the reorder
            pass
        raise
    if changed:
        ZL.restore_order(zulip)
    return SyncResult(steps if changed else [], live_project_ids(zulip, list(projects)))


_TARGET_ROW_RE = re.compile(
    r'\(\s*(None|\d+)\s*,\s*"(P-[A-Z]+-[0-9]+)"\s*,\s*"([^"]+)"\s*,?\s*\)',
    re.DOTALL,
)


def _parse_target_rows(text: str) -> dict[str, tuple[int | None, str]]:
    rows: dict[str, tuple[int | None, str]] = {}
    for match in _TARGET_ROW_RE.finditer(text):
        raw_id, code, url = match.groups()
        rows[code] = (int(raw_id) if raw_id != "None" else None, url)
    return rows


def _format_target_row(rule_id: int | None, code: str, url: str) -> str:
    one = '    (%s, "%s", "%s"),' % ("None" if rule_id is None else rule_id, code, url)
    if len(one) <= 100:
        return one
    return '    (\n        %s,\n        "%s",\n        "%s",\n    ),' % (
        "None" if rule_id is None else rule_id,
        code,
        url,
    )


def rewrite_target(text: str, projects: list[Project], ids: dict[str, int | None] | None) -> str:
    """The zulip_linkifiers.py text with the P-* rows generated from Linear.  The
    union of existing rows and Linear projects (Linear winning on the URL);  rows
    for codes Linear no longer lists are kept.  Idempotent, deterministic."""
    ids = ids or {}
    existing = _parse_target_rows(text)
    by_code = {p.code: p for p in projects}
    codes = sorted(set(existing) | set(by_code), key=_code_sort_key)
    rows = []
    for code in codes:
        if code in by_code:
            url = project_url(by_code[code].slug)
            rule_id = ids.get(code)
        else:
            rule_id, url = existing[code]
        rows.append(_format_target_row(rule_id, code, url))
    block = "\n".join([TARGET_BEGIN, *rows, TARGET_END])
    if TARGET_BEGIN in text and TARGET_END in text:
        before, _, rest = text.partition(TARGET_BEGIN)
        _, _, after = rest.partition(TARGET_END)
        return before + block + after
    start_marker = "# Linear projects, one literal rule each"
    start = text.find(start_marker)
    if start == -1:
        raise ValueError("TARGET has no linear-projects block to rewrite")
    line_start = text.rfind("\n", 0, start) + 1
    generic = text.find('(5139, "(?P<repo>')
    if generic == -1:
        generic = text.find("(5139,")
    if generic == -1 or generic < line_start:
        raise ValueError("TARGET has no generic rule to anchor the rewrite")
    generic_line = text.rfind("\n", 0, generic) + 1
    return text[:line_start] + TARGET_COMMENT + "\n" + block + "\n" + text[generic_line:]


_PATHS_ENTRY_RE = re.compile(r'"(P-[A-Z]+-[0-9]+)"\s*:\s*"([^"]*)"')
_PATHS_COMMENT_RE = re.compile(r"#\s{2,}(.*), which the fleet calls (P-[A-Z]+-[0-9]+)\.")


def _project_paths_block(text: str) -> tuple[int, int]:
    start = text.find("PROJECT_PATHS = {")
    if start == -1:
        raise ValueError("PROJECT_PATHS is missing")
    brace = text.find("{", start)
    depth = 0
    for offset, char in enumerate(text[brace:]):
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return brace, brace + offset + 1
    raise ValueError("PROJECT_PATHS is never closed")


def _parse_project_paths(text: str) -> dict[str, tuple[str, str | None]]:
    """Existing PROJECT_PATHS as code -> (path, preceding comment line or None)."""
    brace, end = _project_paths_block(text)
    inner = text[brace:end]
    entries: dict[str, tuple[str, str | None]] = {}
    comments: dict[str, str] = {}
    for line in inner.splitlines():
        commented = _PATHS_COMMENT_RE.search(line)
        if commented:
            comments[commented.group(2)] = line.rstrip("\n")
    for match in _PATHS_ENTRY_RE.finditer(inner):
        code, path = match.groups()
        entries[code] = (path, comments.get(code))
    return entries


def _paths_comment(code: str, name: str) -> str:
    return "    #  %s, which the fleet calls %s." % (sanitize_name(name) or code, code)


def rewrite_project_paths(text: str, projects: list[Project]) -> str:
    """The apple-notes-coding.sh text with PROJECT_PATHS generated from Linear:
    code -> slugId (ID-only; PROJECT_URLS builds the ID-only URL).  Entries for
    codes Linear no longer lists are kept.  Idempotent, deterministic."""
    existing = _parse_project_paths(text)
    by_code = {p.code: p for p in projects}
    codes = sorted(set(existing) | set(by_code), key=_code_sort_key)
    lines = [TARGET_BEGIN]
    for code in codes:
        if code in by_code:
            lines.append(_paths_comment(code, by_code[code].name))
            lines.append('    "%s": "%s",' % (code, by_code[code].slug))
        else:
            path, comment = existing[code]
            lines.append(comment if comment is not None else _paths_comment(code, code))
            lines.append('    "%s": "%s",' % (code, path))
    lines.append(TARGET_END)
    block = "\n".join(lines)
    brace, end = _project_paths_block(text)
    inner = text[brace:end]
    if TARGET_BEGIN in inner and TARGET_END in inner:
        before, _, rest = text.partition(TARGET_BEGIN)
        kept, _, after = rest.partition(TARGET_END)
        del kept
        return before + block + after
    return text[: brace + 1] + "\n" + block + "\n" + text[end - 1 :]


HttpFn = Callable[[str, str, dict[str, str] | None, bytes | None], tuple[int, Any]]


def _default_http(
    method: str, url: str, headers: dict[str, str] | None = None, body: bytes | None = None
) -> tuple[int, Any]:
    req = urllib.request.Request(url, data=body, headers=headers or {}, method=method)
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            status = getattr(resp, "status", 200)
            raw = resp.read()
    except urllib.error.HTTPError as exc:
        try:
            raw = exc.read()
        except OSError:
            raw = b""
        try:
            return exc.code, json.loads(raw or b"{}")
        except ValueError:
            return exc.code, {}
    try:
        return status, json.loads(raw.decode("utf-8") if raw else "{}")
    except ValueError:
        return status, {}


def _short_message(payload: Any) -> str:
    if isinstance(payload, dict):
        message = payload.get("message", "")
        if isinstance(message, str) and message:
            return message[:200]
        errors = payload.get("errors")
        if isinstance(errors, list) and errors and isinstance(errors[0], dict):
            first = str(errors[0].get("message", ""))[:200]
            if first:
                return first
    return ""


def _github_headers(github_token: str) -> dict[str, str]:
    return {
        "Authorization": "Bearer " + github_token,
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "User-Agent": "operator-linkifiers",
    }


def _github_api(
    http: HttpFn, headers: dict[str, str], method: str, url: str, body: Any = None
) -> Any:
    data = None if body is None else json.dumps(body).encode("utf-8")
    try:
        status, payload = http(method, url, headers, data)
    except OSError as exc:
        raise GitHubError("GitHub %s: %s" % (url, type(exc).__name__)) from None
    if status is None:
        raise GitHubError("GitHub %s: no response" % url)
    if 200 <= int(status) < 300:
        return payload
    message = _short_message(payload)
    path = urllib.parse.urlsplit(url).path
    raise GitHubError(
        "GitHub %s %s: HTTP %s%s" % (method, path, status, (" " + message) if message else "")
    )


def _github_get(http: HttpFn, headers: dict[str, str], url: str) -> tuple[int, Any]:
    try:
        return http("GET", url, headers, None)
    except OSError as exc:
        raise GitHubError("GitHub %s: %s" % (url, type(exc).__name__)) from None


def _branch_name(files: dict[str, str]) -> str:
    joined = "\n".join("%s\x00%s" % pair for pair in sorted(files.items()))
    digest = hashlib.sha256(joined.encode("utf-8")).hexdigest()[:10]
    return "operator/linear-projects-" + digest


def _code_of(item: Any) -> str:
    code = getattr(item, "code", None)
    return str(code) if code is not None else str(item)


def _slug_of(item: Any) -> str | None:
    slug = getattr(item, "slug", None)
    return str(slug) if slug else None


def _pr_body(codes: list[Any]) -> str:
    gap = "\u00a0 "  # a real U+00A0 followed by a normal space
    lines = [
        "Generated by the Operator's Linear project webhook (AFC-565).%sProject links are"
        " ID-only: https://linear.app/simple-with-us/project/<slugId>, which Linear opens"
        " regardless of the project name.%sThis pull request updates TARGET in"
        " scripts/zulip_linkifiers.py and PROJECT_PATHS in scripts/apple-notes-coding.sh"
        " (the generated BEGIN/END blocks)." % (gap, gap),
        "",
    ]
    for item in sorted(codes, key=lambda c: _code_sort_key(_code_of(c))):
        slug = _slug_of(item)
        if slug:
            lines.append("- %s -> %s" % (_code_of(item), project_url(slug)))
        else:
            lines.append("- %s" % _code_of(item))
    return "\n".join(lines) + "\n"


def open_sync_pr(
    github_token: str,
    files: dict[str, str],
    codes: list[Any],
    *,
    http: HttpFn | None = None,
) -> dict[str, Any] | None:
    """A ready PR syncing the generated files, or None when main already matches.
    Idempotent:  an existing branch reuses its open PR instead of opening another."""
    request = http or _default_http
    headers = _github_headers(github_token)
    base = "https://api.github.com/repos/" + REPO
    head = _github_api(request, headers, "GET", base + "/git/ref/heads/" + BASE_BRANCH)
    try:
        main_sha = head["object"]["sha"]
    except (KeyError, TypeError):
        raise GitHubError("GitHub main head: unexpected response") from None
    unchanged = True
    for path, want in files.items():
        url = base + "/contents/" + urllib.parse.quote(path) + "?ref=" + BASE_BRANCH
        status, payload = _github_get(request, headers, url)
        if status == 404:
            unchanged = False
            continue
        if not 200 <= int(status) < 300:
            message = _short_message(payload)
            raise GitHubError(
                "GitHub GET contents %s: HTTP %s%s"
                % (path, status, (" " + message) if message else "")
            )
        try:
            have = base64.b64decode("".join(str(payload["content"]).split())).decode("utf-8")
        except (KeyError, ValueError):
            have = ""
        if have != want:
            unchanged = False
    if unchanged:
        return None
    branch = _branch_name(files)
    status, _ = _github_get(request, headers, base + "/git/ref/heads/" + branch)
    if status is not None and 200 <= int(status) < 300:
        query = urllib.parse.urlencode({"head": REPO.split("/")[0] + ":" + branch, "state": "open"})
        found = _github_api(request, headers, "GET", base + "/pulls?" + query)
        if isinstance(found, list) and found:
            first = found[0]
            return dict(first) if isinstance(first, dict) else {"html_url": str(first)}
        return None
    if status != 404:
        message = ""
        raise GitHubError("GitHub branch check: HTTP %s%s" % (status, message))
    names = ", ".join(_code_of(c) for c in sorted(codes, key=lambda c: _code_sort_key(_code_of(c))))
    commit_message = "chore(linkifiers): sync Linear project links (%s) [AFC-565]" % names
    blobs = []
    for path in sorted(files):
        created = _github_api(
            request,
            headers,
            "POST",
            base + "/git/blobs",
            {"content": files[path], "encoding": "utf-8"},
        )
        try:
            blobs.append((path, created["sha"]))
        except (KeyError, TypeError):
            raise GitHubError("GitHub blob: unexpected response") from None
    commit = _github_api(request, headers, "GET", base + "/git/commits/" + main_sha)
    try:
        base_tree = commit["tree"]["sha"]
    except (KeyError, TypeError):
        raise GitHubError("GitHub commit: unexpected response") from None
    tree = _github_api(
        request,
        headers,
        "POST",
        base + "/git/trees",
        {
            "base_tree": base_tree,
            "tree": [
                {"path": path, "mode": "100644", "type": "blob", "sha": sha} for path, sha in blobs
            ],
        },
    )
    try:
        tree_sha = tree["sha"]
    except (KeyError, TypeError):
        raise GitHubError("GitHub tree: unexpected response") from None
    new_commit = _github_api(
        request,
        headers,
        "POST",
        base + "/git/commits",
        {"message": commit_message, "tree": tree_sha, "parents": [main_sha]},
    )
    try:
        new_sha = new_commit["sha"]
    except (KeyError, TypeError):
        raise GitHubError("GitHub commit: unexpected response") from None
    _github_api(
        request,
        headers,
        "POST",
        base + "/git/refs",
        {"ref": "refs/heads/" + branch, "sha": new_sha},
    )
    pr = _github_api(
        request,
        headers,
        "POST",
        base + "/pulls",
        {
            "title": "chore(linkifiers): sync Linear project links (%s)" % names,
            "head": branch,
            "base": BASE_BRANCH,
            "body": _pr_body(list(codes)),
            "draft": False,
        },
    )
    return dict(pr) if isinstance(pr, dict) else {"html_url": str(pr)}


def _infisical_get(http: HttpFn, url: str, service_token: str) -> Any:
    headers = {"Authorization": "Bearer " + service_token, "Accept": "application/json"}
    try:
        status, payload = http("GET", url, headers, None)
    except OSError as exc:
        raise SecretsRefused("infisical_error", "Infisical: %s" % type(exc).__name__) from None
    if status is None or not 200 <= int(status) < 300:
        message = _short_message(payload)
        raise SecretsRefused(
            "infisical_error",
            "Infisical: HTTP %s%s" % (status, (" " + message) if message else ""),
        )
    return payload


def load_secrets(service_token: str, *, http: HttpFn | None = None) -> dict[str, str]:
    """The five linkifier secrets from Infisical, the ONLY source (owner policy
    2026-10-26).  The service token must be read-only and scoped to exactly
    prod:/operator-linkifiers, else SecretsRefused.  Missing names stay absent."""
    request = http or _default_http
    record = _infisical_get(request, INFISICAL_API + "/v2/service-token", service_token)
    if not isinstance(record, dict):
        raise SecretsRefused("token_invalid", "the service-token record is not an object")
    permissions = record.get("permissions", [])
    if isinstance(permissions, dict):
        permissions = list(permissions)
    if not isinstance(permissions, list):
        permissions = []
    lowered = [str(p).lower() for p in permissions]
    if "write" in lowered or "read" not in lowered:
        raise SecretsRefused("token_not_read_only", "the service token is not read-only")
    scopes = record.get("scopes", record.get("scope", []))
    if isinstance(scopes, dict):
        scopes = [scopes]
    if not isinstance(scopes, list) or len(scopes) != 1:
        raise SecretsRefused(
            "token_scope_mismatch",
            "the service token must be scoped to exactly %s:%s" % (SECRET_ENV, SECRET_FOLDER),
        )
    scope = scopes[0]
    if (
        not isinstance(scope, dict)
        or scope.get("environment") != SECRET_ENV
        or scope.get("secretPath") != SECRET_FOLDER
    ):
        raise SecretsRefused(
            "token_scope_mismatch",
            "the service token must be scoped to exactly %s:%s" % (SECRET_ENV, SECRET_FOLDER),
        )
    workspace = record.get("workspace")
    if not isinstance(workspace, str) or not workspace:
        raise SecretsRefused("token_invalid", "the service-token record names no workspace")
    query = urllib.parse.urlencode(
        {"workspaceId": workspace, "environment": SECRET_ENV, "secretPath": SECRET_FOLDER}
    )
    raw = _infisical_get(request, INFISICAL_API + "/v3/secrets/raw?" + query, service_token)
    items: Any = raw.get("secrets", raw) if isinstance(raw, dict) else raw
    if not isinstance(items, list):
        items = []
    found: dict[str, str] = {}
    for item in items:
        if not isinstance(item, dict):
            continue
        key = item.get("secretKey", item.get("key", item.get("name")))
        value = item.get("secretValue", item.get("value"))
        if isinstance(key, str) and isinstance(value, str) and key in SECRET_NAMES:
            found[key] = value
    return found


def read_token_file(path: str) -> str:
    """The bootstrap service token from a 0600 file.  Refuses group/other-readable
    files.  Never returns the token's value in an error."""
    try:
        mode = stat.S_IMODE(os.stat(path).st_mode)
    except OSError:
        raise SecretsRefused("token_file_unreadable", "cannot read the token file") from None
    if mode & 0o077:
        raise SecretsRefused(
            "token_file_permissions", "the token file must not be group/other readable"
        )
    try:
        with open(path, encoding="utf-8") as handle:
            token = handle.read().strip()
    except OSError:
        raise SecretsRefused("token_file_unreadable", "cannot read the token file") from None
    if not token:
        raise SecretsRefused("token_file_empty", "the token file is empty")
    return token


def verify_linear_webhook(
    raw_body: bytes, signature: str | None, secret: str, now_ms: int
) -> dict[str, Any]:
    """The verified Linear webhook payload.  JSON is parsed only after the
    HMAC-SHA256 signature matches;  the timestamp must be within 60 s of now."""
    if not isinstance(secret, str) or len(secret) < 16:
        raise WebhookRefused(503, "not_configured")
    if not isinstance(raw_body, (bytes, bytearray)):
        raise WebhookRefused(400, "bad_json")
    expected = hmac.new(secret.encode("utf-8"), bytes(raw_body), hashlib.sha256).hexdigest()
    if not signature or not hmac.compare_digest(expected, str(signature).strip().lower()):
        raise WebhookRefused(401, "bad_signature")
    try:
        payload = json.loads(bytes(raw_body).decode("utf-8"))
    except (ValueError, UnicodeError):
        raise WebhookRefused(400, "bad_json") from None
    if not isinstance(payload, dict):
        raise WebhookRefused(400, "bad_json")
    stamp = payload.get("webhookTimestamp")
    if isinstance(stamp, bool) or not isinstance(stamp, (int, float)):
        raise WebhookRefused(401, "stale_timestamp")
    if abs(int(now_ms) - int(stamp)) > WEBHOOK_WINDOW_MS:
        raise WebhookRefused(401, "stale_timestamp")
    return payload


def _repo_root(repo_root: Path | None) -> Path:
    if repo_root is not None:
        return Path(repo_root)
    return Path(__file__).resolve().parent.parent


def _github_file_text(http: HttpFn, github_token: str, path: str) -> str | None:
    headers = _github_headers(github_token)
    url = (
        "https://api.github.com/repos/"
        + REPO
        + "/contents/"
        + urllib.parse.quote(path)
        + "?ref="
        + BASE_BRANCH
    )
    status, payload = _github_get(http, headers, url)
    if status == 404:
        return None
    if not 200 <= int(status) < 300:
        message = _short_message(payload)
        raise GitHubError(
            "GitHub GET contents %s: HTTP %s%s" % (path, status, (" " + message) if message else "")
        )
    try:
        return base64.b64decode("".join(str(payload["content"]).split())).decode("utf-8")
    except (KeyError, ValueError):
        raise GitHubError("GitHub contents %s: unexpected response" % path) from None


def reconcile(
    secrets: dict[str, str],
    *,
    apply_zulip: bool = False,
    open_pr: bool = False,
    repo_root: Path | None = None,
    write_files: bool = False,
    zulip_factory: Callable[[], Any] | None = None,
    http: HttpFn | None = None,
    opener: Callable[..., Any] | None = None,
    fetch_fn: Callable[..., Any] | None = None,
) -> dict[str, Any]:
    """Fetch Linear projects, upsert the live Zulip rules, and sync the repo
    files (locally with write_files, via a PR from GitHub main with open_pr)."""
    linear_key = (secrets or {}).get("LINEAR_API_KEY", "")
    if not linear_key:
        raise LinearError("LINEAR_API_KEY is not configured")
    if fetch_fn is not None:
        result = fetch_fn(linear_key)
        if isinstance(result, tuple) and len(result) == 2 and isinstance(result[1], int):
            projects, skipped = result
        else:
            projects, skipped = result, getattr(fetch_fn, "last_skipped", 0)
    elif opener is not None:
        projects, skipped = fetch_projects_with_stats(linear_key, opener=opener)
    else:
        projects, skipped = fetch_projects_with_stats(linear_key)
    projects = list(projects)
    actions: list[tuple] = []
    ids: dict[str, int | None] = {}
    if apply_zulip:
        email = (secrets or {}).get("ZULIP_OPERATOR_EMAIL", "")
        key = (secrets or {}).get("ZULIP_OPERATOR_API_KEY", "")
        if zulip_factory is None:
            if not (email and key):
                raise LinearError("ZULIP_OPERATOR_EMAIL / ZULIP_OPERATOR_API_KEY are missing")
            import zulip_linkifiers as ZL

            def zulip_factory() -> Any:
                return ZL.Zulip(email, key, ZL.REALM)

        result = sync_zulip(zulip_factory(), projects)
        actions = list(result)
        ids = dict(result.ids)
    elif zulip_factory is not None:
        try:
            ids = live_project_ids(zulip_factory(), projects)
        except Exception:  # noqa: BLE001 - without live ids the rows pin None, still matchable
            ids = {}
    codes = [p.code for p in projects]
    urls = {p.code: project_url(p.slug) for p in projects}
    pr_url: str | None = None
    pr: dict[str, Any] | None = None
    written: list[str] = []
    if open_pr or write_files:
        new_files: dict[str, str] = {}
        if open_pr:
            github_token = (secrets or {}).get("GITHUB_TOKEN", "")
            if not github_token:
                raise GitHubError("GITHUB_TOKEN is not configured")
            request = http or _default_http
            for path in (TARGET_PATH, PROJECT_PATHS_PATH):
                base_text = _github_file_text(request, github_token, path)
                if base_text is None:
                    raise GitHubError("GitHub main has no %s" % path)
                if path == TARGET_PATH:
                    new_files[path] = rewrite_target(base_text, projects, ids)
                else:
                    new_files[path] = rewrite_project_paths(base_text, projects)
            pr = open_sync_pr(github_token, new_files, projects, http=request)
            if pr is not None:
                pr_url = str(pr.get("html_url") or pr.get("url") or "")
        if write_files:
            root = _repo_root(repo_root)
            for path in (TARGET_PATH, PROJECT_PATHS_PATH):
                local = root / path
                base_text = local.read_text(encoding="utf-8")
                if path == TARGET_PATH:
                    updated = rewrite_target(base_text, projects, ids)
                else:
                    updated = rewrite_project_paths(base_text, projects)
                if updated != base_text:
                    local.write_text(updated, encoding="utf-8")
                    written.append(path)
    return {
        "codes": codes,
        "urls": urls,
        "zulip_actions": actions,
        "actions": actions,
        "pr_url": pr_url,
        "pr": pr,
        "skipped": skipped,
        "skipped_projects": skipped,
        "ids": ids,
        "written": written,
    }


def _print_plan(
    projects: list[Project],
    actions: list[tuple],
    diffs: list[tuple[str, str, str]],
    out: Any = sys.stdout,
) -> None:
    for project in projects:
        out.write("%s -> %s\n" % (project.code, project_url(project.slug)))
    if not actions:
        out.write("zulip: no changes\n")
    for kind, rule_id, code, url in actions:
        out.write("zulip %s %s %s -> %s\n" % (kind, rule_id or "new", code, url))
    for path, before, after in diffs:
        if before == after:
            out.write("%s: no changes\n" % path)
            continue
        out.write(
            "".join(
                difflib.unified_diff(
                    before.splitlines(keepends=True),
                    after.splitlines(keepends=True),
                    fromfile="a/" + path,
                    tofile="b/" + path,
                )
            )
        )
        if not out.closed:
            out.flush()


def _zulip_factory_from(secrets: dict[str, str]) -> Callable[[], Any]:
    email = secrets.get("ZULIP_OPERATOR_EMAIL", "")
    key = secrets.get("ZULIP_OPERATOR_API_KEY", "")
    if not (email and key):
        raise LinearError("ZULIP_OPERATOR_EMAIL / ZULIP_OPERATOR_API_KEY are missing")

    def build() -> Any:
        import zulip_linkifiers as ZL

        return ZL.Zulip(email, key, ZL.REALM)

    return build


def cmd_plan(token_file: str, out: Any = sys.stdout) -> int:
    try:
        secrets = load_secrets(read_token_file(token_file))
        projects, skipped = fetch_projects_with_stats(secrets.get("LINEAR_API_KEY", ""))
    except (SecretsRefused, LinearError) as exc:
        print("plan: %s" % exc, file=sys.stderr)
        return 1
    try:
        live = _zulip_factory_from(secrets)().linkifiers()
    except SystemExit as exc:
        print("plan: zulip: %s" % exc, file=sys.stderr)
        return 1
    except OSError as exc:
        print("plan: zulip: %s" % type(exc).__name__, file=sys.stderr)
        return 1
    actions = _plan_zulip_actions(live, projects)
    by_pattern = {r.get("pattern"): r for r in live if isinstance(r, dict)}
    ids = {
        p.code: (
            by_pattern[p.code].get("id")
            if isinstance(by_pattern.get(p.code), dict)
            and isinstance(by_pattern[p.code].get("id"), int)
            else None
        )
        for p in projects
    }
    root = _repo_root(None)
    diffs = []
    for path in (TARGET_PATH, PROJECT_PATHS_PATH):
        try:
            before = (root / path).read_text(encoding="utf-8")
        except OSError as exc:
            print("plan: %s: %s" % (path, exc.strerror or "unreadable"), file=sys.stderr)
            return 1
        after = (
            rewrite_target(before, projects, ids)
            if path == TARGET_PATH
            else rewrite_project_paths(before, projects)
        )
        diffs.append((path, before, after))
    _print_plan(projects, actions, diffs, out)
    if skipped:
        out.write("skipped %d Linear node(s) with a bad identifier or slugId\n" % skipped)
    return 0


def cmd_backfill(
    token_file: str,
    *,
    apply_zulip_flag: bool = False,
    write_files_flag: bool = False,
    open_pr_flag: bool = False,
    out: Any = sys.stdout,
) -> int:
    try:
        secrets = load_secrets(read_token_file(token_file))
    except SecretsRefused as exc:
        print("backfill: %s" % exc, file=sys.stderr)
        return 1
    factory: Callable[[], Any] | None = None
    if apply_zulip_flag or write_files_flag or open_pr_flag:
        try:
            factory = _zulip_factory_from(secrets)
        except LinearError:
            factory = None
            if apply_zulip_flag:
                print(
                    "backfill: ZULIP_OPERATOR_EMAIL / ZULIP_OPERATOR_API_KEY are missing",
                    file=sys.stderr,
                )
                return 1
    try:
        summary = reconcile(
            secrets,
            apply_zulip=apply_zulip_flag,
            open_pr=open_pr_flag,
            write_files=write_files_flag,
            zulip_factory=factory,
        )
    except (LinearError, GitHubError, SecretsRefused, OSError, ValueError) as exc:
        print("backfill: %s" % exc, file=sys.stderr)
        return 1
    for code in summary["codes"]:
        out.write("%s -> %s\n" % (code, summary["urls"][code]))
    for kind, rule_id, code, url in summary["zulip_actions"]:
        out.write("zulip %s %s %s -> %s\n" % (kind, rule_id or "new", code, url))
    if summary["pr_url"]:
        out.write("pr %s\n" % summary["pr_url"])
    elif open_pr_flag:
        out.write("pr: no changes\n")
    for path in summary["written"]:
        out.write("wrote %s\n" % path)
    if summary["skipped"]:
        out.write(
            "skipped %d Linear node(s) with a bad identifier or slugId\n" % summary["skipped"]
        )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    plan = sub.add_parser("plan", help="print planned Zulip actions and file diffs")
    plan.add_argument("--token-file", required=True, help="a 0600 file holding the bootstrap token")
    fill = sub.add_parser("backfill", help="fetch Linear projects and sync them")
    fill.add_argument("--token-file", required=True, help="a 0600 file holding the bootstrap token")
    fill.add_argument("--apply-zulip", action="store_true", help="upsert the live Zulip rules")
    fill.add_argument("--write-files", action="store_true", help="rewrite the local repo files")
    fill.add_argument("--open-pr", action="store_true", help="open a GitHub sync PR from main")
    args = parser.parse_args(argv)
    if args.command == "plan":
        return cmd_plan(args.token_file)
    return cmd_backfill(
        args.token_file,
        apply_zulip_flag=args.apply_zulip,
        write_files_flag=args.write_files,
        open_pr_flag=args.open_pr,
    )


if __name__ == "__main__":
    sys.exit(main())
