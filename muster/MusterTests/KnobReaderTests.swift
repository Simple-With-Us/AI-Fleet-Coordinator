import XCTest
/// The controls registry reader:  what it reads,  and what it refuses to show.
final class KnobReaderTests: XCTestCase {
    /// The project and environment the engine's own copy carries.
    ///
    /// The app does not know these,  so the tests use the shape the engine answers
    /// with rather than a value of the engine's own.
    static let project = "test-infisical-project"
    static let environment = "prod"

    /// The identity the engine would give.
    private var identity: EngineIdentity.Identity {
        EngineIdentity.Identity(project: Self.project, environment: Self.environment)
    }
    /// A repo with a generated registry block,  and a local copy beside it.
    private func makeRepo() throws -> (root: URL, home: URL) {
        let base = URL(fileURLWithPath: NSTemporaryDirectory())
            .appendingPathComponent("muster-knobs-\(UUID().uuidString)", isDirectory: true)
        let root = base.appendingPathComponent("repo", isDirectory: true)
        let home = base.appendingPathComponent("home", isDirectory: true)
        try FileManager.default.createDirectory(
            at: root.appendingPathComponent("scripts", isDirectory: true),
            withIntermediateDirectories: true
        )
        let copyDirectory = home.appendingPathComponent(".local/state/fleet-knobs", isDirectory: true)
        try FileManager.default.createDirectory(
            at: copyDirectory,
            withIntermediateDirectories: true
        )
        // The engine keeps the copy's directory private,  and the reader checks it.
        try FileManager.default.setAttributes(
            [.posixPermissions: 0o700],
            ofItemAtPath: copyDirectory.path
        )
        try """
        # Infisical

        <!-- fleet-knobs:begin  generated by `python3 -m fleet_knobs inventory --write ../INFISICAL.md`;  edit scripts/fleet_knobs/registry.py, not this block -->

        | Key | Owner | Kind | Default | Secret | Local files may | What it does |
        |---|---|---|---|---|---|---|
        | `FLEET_AUTOPUSH_MODE` | C1 | enum: off < report | `off` | no | only move toward `off` | what the autopush hooks may do |
        | `FLEET_FACTS_SIGNING_KEY` | F7 | str | none, fails closed | secret | nothing | HMAC key for the signed facts files |
        | `FLEET_IDLE_HOURS` | C1 | int 1 to 168 | `2` | no | only raise it | hours a lane sits unchanged |

        <!-- fleet-knobs:end -->
        """.write(
            to: root.appendingPathComponent("INFISICAL.md"),
            atomically: true,
            encoding: .utf8
        )
        return (root, home)
    }

    /// Write a copy the way the engine writes one.
    ///
    /// The engine puts its own identity on every copy,  so a copy without it is one
    /// the engine would refuse.  The age is in seconds before now,  so a negative
    /// age dates the copy in the future.
    private func writeCopy(
        in home: URL,
        knobs: [String: String] = [:],
        age: TimeInterval = 60,
        schema: Int = 1,
        project: String = KnobReaderTests.project,
        environment: String = KnobReaderTests.environment,
        omitTime: Bool = false,
        permissions: NSNumber = 0o600
    ) throws {
        var body: [String: Any] = [
            "schema": schema,
            "project": project,
            "environment": environment,
            "knobs": knobs,
        ]
        if !omitTime {
            body["saved_epoch"] = Date().timeIntervalSince1970 - age
        }
        let data = try JSONSerialization.data(withJSONObject: body)
        let path = home.appendingPathComponent(".local/state/fleet-knobs/lkg.json")
        try data.write(to: path)
        try FileManager.default.setAttributes(
            [.posixPermissions: permissions],
            ofItemAtPath: path.path
        )
    }

    /// The registry is read from the generated block,  and only the knobs in it.
    func test_the_registry_is_read_from_the_generated_block() throws {
        let (root, home) = try makeRepo()
        defer { try? FileManager.default.removeItem(at: root.deletingLastPathComponent()) }
        let registry = KnobReader.read(repoRoot: root, home: home, identity: identity)
        XCTAssertEqual(registry.knobs.count, 3)
        XCTAssertEqual(registry.knobs.first?.name, "FLEET_AUTOPUSH_MODE")
        XCTAssertEqual(registry.knobs.first?.owner, "C1")
        XCTAssertEqual(registry.knobs.first?.kind, "enum: off < report")
        // The registry writes its values in code spans,  and the panel shows the value.
        XCTAssertEqual(registry.knobs.first?.defaultValue, "off")
        XCTAssertEqual(registry.knobs.first?.localMay, "only move toward off")
    }

    /// A knob the copy does not carry holds its default.
    ///
    /// This needs a copy that is there,  because a copy that is missing says the
    /// value is unknown rather than that it is the default.
    ///
    /// The engine answers the same way.  Its own reader drops every knob that is
    /// unset from the copy it writes,  so a knob that is missing from a copy the
    /// engine wrote was unset at the last good fetch,  and the engine's answer for
    /// it is the base default  (`scripts/fleet_knobs/knobs.py`,  `_from_sources`).
    func test_a_knob_with_no_value_in_the_copy_holds_its_default() throws {
        let (root, home) = try makeRepo()
        defer { try? FileManager.default.removeItem(at: root.deletingLastPathComponent()) }
        try writeCopy(in: home, knobs: ["FLEET_IDLE_HOURS": "3"])
        let registry = KnobReader.read(repoRoot: root, home: home, identity: identity)
        let knob = registry.knobs.first { $0.name == "FLEET_AUTOPUSH_MODE" }
        XCTAssertEqual(knob?.current, .defaultValue("off"))
    }

    /// A knob with a value in the copy shows it.
    func test_a_knob_with_a_value_shows_it() throws {
        let (root, home) = try makeRepo()
        defer { try? FileManager.default.removeItem(at: root.deletingLastPathComponent()) }
        try writeCopy(in: home, knobs: ["FLEET_AUTOPUSH_MODE": "report"])
        let registry = KnobReader.read(repoRoot: root, home: home, identity: identity)
        XCTAssertEqual(registry.knobs.first?.current, .current("report"))
    }

    /// A secret knob shows that its presence is unconfirmed,  and never a value.
    ///
    /// The copy holds the non-secret knobs only,  so a secret is never in it and its
    /// absence says nothing about whether the secret is set.  Reporting a secret as
    /// "not set" would be a false statement about a credential that is very likely
    /// set,  so the panel says the presence is unconfirmed instead.
    func test_a_secret_knob_says_its_presence_is_unconfirmed() throws {
        let (root, home) = try makeRepo()
        defer { try? FileManager.default.removeItem(at: root.deletingLastPathComponent()) }
        try writeCopy(in: home, knobs: ["FLEET_AUTOPUSH_MODE": "report"])
        let registry = KnobReader.read(repoRoot: root, home: home, identity: identity)
        let secret = registry.knobs.first { $0.name == "FLEET_FACTS_SIGNING_KEY" }
        XCTAssertEqual(secret?.isSecret, true)
        XCTAssertEqual(secret?.current, KnobRegistry.Knob.CurrentValue.secretUnconfirmed)
        XCTAssertFalse(secret?.current.displayText.contains("a-secret-value") ?? true)
    }

    /// A secret row shows no value,  and the row model says it is a secret.
    func test_a_secret_row_shows_no_value() throws {
        let (root, home) = try makeRepo()
        defer { try? FileManager.default.removeItem(at: root.deletingLastPathComponent()) }
        try writeCopy(in: home, knobs: ["FLEET_AUTOPUSH_MODE": "report"])
        let registry = KnobReader.read(repoRoot: root, home: home, identity: identity)
        let row = registry.rows.first { $0.name == "FLEET_FACTS_SIGNING_KEY" }
        XCTAssertEqual(row?.nowIsSecret, true)
        XCTAssertEqual(row?.now, "not known (secret)")
        // The whole row carries no value anywhere.
        let text = [row?.now, row?.owner, row?.kind, row?.localMay, row?.note]
            .compactMap { $0 }
            .joined(separator: " ")
        XCTAssertFalse(text.contains("a-secret-value"))
    }

    /// A secret column that says something the app does not know still fails closed.
    ///
    /// The column is "no" or "secret".  Any other wording must not have a secret's
    /// value shown in plain text,  so anything but "no" is treated as a secret.
    func test_an_unknown_secret_column_fails_closed() throws {
        let (root, home) = try makeRepo()
        defer { try? FileManager.default.removeItem(at: root.deletingLastPathComponent()) }
        try """
        # Infisical

        <!-- fleet-knobs:begin -->

        | Key | Owner | Kind | Default | Secret | Local files may | What it does |
        |---|---|---|---|---|---|---|
        | `FLEET_FACTS_SIGNING_KEY` | F7 | str | none | YES | nothing | HMAC key |

        <!-- fleet-knobs:end -->
        """.write(
            to: root.appendingPathComponent("INFISICAL.md"),
            atomically: true,
            encoding: .utf8
        )
        try writeCopy(in: home, knobs: ["FLEET_FACTS_SIGNING_KEY": "a-secret-value"])
        let registry = KnobReader.read(repoRoot: root, home: home, identity: identity)
        let knob = registry.knobs.first { $0.name == "FLEET_FACTS_SIGNING_KEY" }
        XCTAssertEqual(knob?.isSecret, true)
        XCTAssertEqual(knob?.current, KnobRegistry.Knob.CurrentValue.secretUnconfirmed)
        XCTAssertFalse(knob?.current.displayText.contains("a-secret-value") ?? true)
    }

    /// A row with a missing cell is counted,  not dropped in silence.
    ///
    /// The engine leaves out a knob with no note,  so the row has an empty cell in
    /// it.  Dropping the empty cells would move every later value one column to the
    /// left,  so the reader keeps them and counts a row it cannot read.
    func test_a_row_with_a_missing_cell_is_counted() throws {
        let (root, home) = try makeRepo()
        defer { try? FileManager.default.removeItem(at: root.deletingLastPathComponent()) }
        try """
        # Infisical

        <!-- fleet-knobs:begin -->

        | Key | Owner | Kind | Default | Secret | Local files may | What it does |
        |---|---|---|---|---|---|---|
        | `FLEET_IDLE_HOURS` | C1 | int 1 to 168 | `2` | no | only raise it |
        | `FLEET_AUTOPUSH_MODE` | C1 | enum: off < report | `off` | no | only move toward `off` | what the autopush hooks may do |

        <!-- fleet-knobs:end -->
        """.write(
            to: root.appendingPathComponent("INFISICAL.md"),
            atomically: true,
            encoding: .utf8
        )
        let registry = KnobReader.read(repoRoot: root, home: home, identity: identity)
        XCTAssertEqual(registry.unreadableRows, 1)
        // The good row beside it still reads,  and its columns are in the right places.
        let knob = registry.knobs.first { $0.name == "FLEET_AUTOPUSH_MODE" }
        XCTAssertEqual(knob?.owner, "C1")
        XCTAssertEqual(knob?.localMay, "only move toward off")
    }

